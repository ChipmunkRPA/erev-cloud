let regionNames: Intl.DisplayNames | null | undefined;

/** The English short name of an alpha-2 code, else the code itself. */
export function countryName(code: string): string {
  if (regionNames === undefined) {
    try {
      regionNames = new Intl.DisplayNames(["en"], { type: "region" });
    } catch {
      regionNames = null;
    }
  }
  try {
    return regionNames?.of(code) ?? code;
  } catch {
    return code;
  }
}

export interface ReferenceOption {
  readonly value: string;
  readonly label: string;
}

/** "US · United States" options in code order. */
export function countryOptions(): readonly ReferenceOption[] {
  return COUNTRY_CODES.map((code) => ({ value: code, label: `${code} · ${countryName(code)}` }));
}

let zones: readonly string[] | undefined;

/** The IANA time zones the runtime knows, alphabetical; the API rejects unknown names. */
export function timeZones(): readonly string[] {
  if (zones === undefined) {
    try {
      zones = Intl.supportedValuesOf("timeZone");
    } catch {
      zones = [];
    }
  }
  return zones;
}

/** Options of `timeZones()`, always including `current` so an unknown stored zone stays selectable. */
export function timeZoneOptions(current: string | null): readonly ReferenceOption[] {
  const known = timeZones();
  const all =
    current !== null && current !== "" && !known.includes(current) ? [...known, current] : known;
  return all.map((zone) => ({ value: zone, label: zone }));
}
